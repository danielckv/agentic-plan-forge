/**
 * Generate standalone Ajv validators for the shared contract schemas.
 *
 * The bridge serves the UI under `default-src 'self'` with no `'unsafe-eval'`
 * (`internal/relay/local_ws.go`, `BridgeCSP`), so Ajv must never compile a
 * schema in the browser: `ajv.compile()` builds validators with `new Function`,
 * which Chrome refuses under that policy and which aborted the entry module
 * before React mounted.
 *
 * Compilation therefore happens here, at build time, and the output is plain
 * ES module source. The schemas in `internal/contracts/schema/` stay the single
 * source of truth for both Go and the frontend; nothing is copied or
 * re-declared on the TypeScript side.
 */

import { mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";

const schemaDir = fileURLToPath(new URL("../../internal/contracts/schema/", import.meta.url));
const outDir = fileURLToPath(new URL("../src/protocol/", import.meta.url));
const outJS = path.join(outDir, "validators.generated.js");
const outDTS = path.join(outDir, "validators.generated.d.ts");

/** Schema id -> exported identifier. `protocol/schema.ts` imports these names. */
const EXPORTS = {
  "envelope.v1": "envelopeV1",
  "normalized_prd.v1": "normalizedPrdV1",
  "impact_map.v1": "impactMapV1",
  "synthesis.v1": "synthesisV1",
  "research_finding.v1": "researchFindingV1",
};

/**
 * Rewrite Ajv's CommonJS runtime references as static imports.
 *
 * Ajv emits every runtime helper and the ajv-formats table as
 * `require("<module>").<export>` (see `ajv/dist/runtime/*.js` and
 * `ajv-formats/dist/index.js`), and its `code.esm` option only changes the
 * export syntax, not these references. A bare `require` in an ES module
 * reaches the browser unresolved, so each distinct reference becomes one
 * hoisted import with a stable identifier.
 *
 * `.default` needs care. Ajv's runtime helpers are CJS modules that set
 * `exports.default = fn` next to `__esModule`. This package is `type: module`,
 * so the bundler (Rolldown) treats the importer with Node ESM semantics, where
 * the `default` import of a CJS module is the whole `module.exports` object,
 * not `exports.default`. A named `{ default as x }` import therefore hands the
 * validators `{ default, __esModule }` instead of `ucs2length`, and the first
 * `minLength` check throws `x is not a function`. The `default` reference is
 * imported as the module default and unwrapped when it still carries the
 * `__esModule` envelope, which is correct under both interop conventions.
 */
function hoistRequires(body) {
  const seen = new Map();
  const imports = [];
  const unwraps = [];
  const rewritten = body.replace(
    /require\("([^"\\]+)"\)\.([A-Za-z_$][\w$]*)/g,
    (_match, moduleId, exportName) => {
      const key = `${moduleId}#${exportName}`;
      let ident = seen.get(key);
      if (ident === undefined) {
        ident = `__ajv${seen.size}_${exportName.replace(/[^\w$]/g, "")}`;
        seen.set(key, ident);
        if (exportName === "default") {
          imports.push(`import ${ident}_module from ${JSON.stringify(moduleId)};`);
          unwraps.push(`const ${ident} = __ajvUnwrapDefault(${ident}_module);`);
        } else {
          imports.push(`import { ${exportName} as ${ident} } from ${JSON.stringify(moduleId)};`);
        }
      }
      return ident;
    },
  );
  if (/\brequire\s*\(/.test(rewritten)) {
    throw new Error("generated validators still reference require(); the Ajv emit shape changed");
  }
  const helper =
    unwraps.length === 0
      ? ""
      : 'const __ajvUnwrapDefault = (m) => (m !== null && typeof m === "object" && m.__esModule === true ? m.default : m);\n' +
        `${unwraps.join("\n")}\n`;
  return `${imports.join("\n")}\n${helper}${rewritten}`;
}

// Options mirror the former in-browser instance exactly: a generated validator
// must accept and reject the same documents the runtime-compiled one did.
const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  allowUnionTypes: true,
  code: { source: true, esm: true },
});
addFormats(ajv);

for (const id of Object.keys(EXPORTS)) {
  const file = path.join(schemaDir, `${id}.json`);
  let schema;
  try {
    schema = JSON.parse(readFileSync(file, "utf8"));
  } catch (err) {
    throw new Error(`read schema ${file}: ${err.message}`);
  }
  ajv.addSchema(schema, id);
}

const byExportName = Object.fromEntries(Object.entries(EXPORTS).map(([id, name]) => [name, id]));
const header = "// Generated by web/scripts/gen-validators.mjs. Do not edit.\n";
const source = header + hoistRequires(standaloneCode(ajv, byExportName)) + "\n";

const types =
  header +
  'import type { ErrorObject } from "ajv";\n\n' +
  "export interface StandaloneValidate {\n" +
  "  (data: unknown): boolean;\n" +
  "  errors?: ErrorObject[] | null;\n" +
  "}\n\n" +
  Object.values(EXPORTS)
    .map((name) => `export declare const ${name}: StandaloneValidate;`)
    .join("\n") +
  "\n";

mkdirSync(outDir, { recursive: true });
for (const [target, text] of [
  [outJS, source],
  [outDTS, types],
]) {
  const tmp = `${target}.tmp`;
  writeFileSync(tmp, text, { mode: 0o644 });
  renameSync(tmp, target);
}

process.stdout.write(`generated ${Object.keys(EXPORTS).length} validators -> ${outJS}\n`);
