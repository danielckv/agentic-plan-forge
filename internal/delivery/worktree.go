//go:build client && !server

// Package delivery takes an approved plan from spec to running code: it opens
// an isolated git worktree, drives the host agent to implement the plan inside
// it, reads back what changed, builds and runs that worktree in a container,
// and deploys the image.
//
// Nothing here ever writes to the repository the owner is working in. Every
// file the agent touches lives in a worktree under the Plan Forge cache, on its
// own branch, and the owner merges it themselves. A plan that builds badly, or
// an agent that goes wrong, therefore costs a directory, never the working tree.
package delivery

import (
	"context"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/danielckv/agentic-plan-forge/internal/config"
)

// BranchPrefix starts every branch this package creates. It is a namespace, so
// an owner can delete every branch Plan Forge made with one glob and never
// catch one of their own.
const BranchPrefix = "plan-forge/"

// gitTimeout is not set here: every git call takes the caller's context, so a
// hung git dies with the request rather than on a timer of its own.

// approvalID is the only identifier that reaches a path or a branch name. It
// is checked rather than escaped: an approval id is generated by this program
// and is always a UUID, so anything else is a bug or an attack, not a name to
// sanitize.
var approvalID = regexp.MustCompile(`^[a-zA-Z0-9][a-zA-Z0-9._-]{0,63}$`)

// ErrInvalidApprovalID reports an approval id that cannot name a directory.
var ErrInvalidApprovalID = errors.New("approval id is not a safe path element")

// ErrNotAGitRepo reports a repository root git does not recognise.
var ErrNotAGitRepo = errors.New("not a git repository")

// Worktree is one approved plan's isolated checkout.
type Worktree struct {
	// Repo is the repository the worktree belongs to.
	Repo string `json:"repo"`
	// Path is the worktree directory. All coding happens here.
	Path string `json:"path"`
	// Branch is the branch the worktree is checked out on.
	Branch string `json:"branch"`
	// Base is the commit the branch started from, so a diff has an anchor
	// even after the agent commits inside the worktree.
	Base string `json:"base"`
}

// WorktreeRoot is where this package keeps its worktrees: one directory per
// approval under the Plan Forge cache, never inside the repository. A worktree
// inside the repository would be picked up by the AST scan, the drift report
// and the owner's own tooling.
func WorktreeRoot() (string, error) {
	cache, err := config.Cache()
	if err != nil {
		return "", err
	}
	return filepath.Join(cache, "worktrees"), nil
}

// OpenWorktree creates the worktree for an approval, or returns the existing
// one. It is safe to call again after a restart: the second call adopts what
// the first made rather than failing on it, which is what lets an interrupted
// build resume.
func OpenWorktree(ctx context.Context, repo, approval string) (Worktree, error) {
	if !approvalID.MatchString(approval) {
		return Worktree{}, fmt.Errorf("%w: %q", ErrInvalidApprovalID, approval)
	}
	top, err := repoRoot(ctx, repo)
	if err != nil {
		return Worktree{}, err
	}
	root, err := WorktreeRoot()
	if err != nil {
		return Worktree{}, err
	}
	if err := os.MkdirAll(root, 0o700); err != nil {
		return Worktree{}, err
	}
	wt := Worktree{Repo: top, Path: filepath.Join(root, approval), Branch: BranchPrefix + approval}

	if existing, err := os.Stat(wt.Path); err == nil && existing.IsDir() {
		base, err := revParse(ctx, wt.Path, "HEAD")
		if err != nil {
			return Worktree{}, fmt.Errorf("adopt worktree %s: %w", wt.Path, err)
		}
		wt.Base = base
		return wt, nil
	}

	head, err := revParse(ctx, top, "HEAD")
	if err != nil {
		return Worktree{}, err
	}
	wt.Base = head
	// -B resets an orphaned branch left by a worktree directory that was
	// removed by hand, so a retry does not fail on "branch already exists".
	out, err := git(ctx, top, "worktree", "add", "-B", wt.Branch, wt.Path, head)
	if err != nil {
		return Worktree{}, fmt.Errorf("create worktree: %w: %s", err, out)
	}
	return wt, nil
}

// RemoveWorktree deletes the worktree and its branch. Uncommitted work in it is
// lost, so the caller asks the owner first; this function does not.
func RemoveWorktree(ctx context.Context, wt Worktree) error {
	if wt.Path == "" || wt.Repo == "" {
		return errors.New("worktree is not open")
	}
	if out, err := git(ctx, wt.Repo, "worktree", "remove", "--force", wt.Path); err != nil {
		// A directory already gone is the state we wanted.
		if _, statErr := os.Stat(wt.Path); !os.IsNotExist(statErr) {
			return fmt.Errorf("remove worktree: %w: %s", err, out)
		}
		if out, err := git(ctx, wt.Repo, "worktree", "prune"); err != nil {
			return fmt.Errorf("prune worktrees: %w: %s", err, out)
		}
	}
	if out, err := git(ctx, wt.Repo, "branch", "-D", wt.Branch); err != nil {
		return fmt.Errorf("delete branch %s: %w: %s", wt.Branch, err, out)
	}
	return nil
}

// repoRoot resolves the top level of the repository containing dir, so a
// worktree is always added from the real root and never from a subdirectory.
func repoRoot(ctx context.Context, dir string) (string, error) {
	out, err := git(ctx, dir, "rev-parse", "--show-toplevel")
	if err != nil {
		return "", fmt.Errorf("%w: %s", ErrNotAGitRepo, dir)
	}
	return strings.TrimSpace(out), nil
}

func revParse(ctx context.Context, dir, ref string) (string, error) {
	out, err := git(ctx, dir, "rev-parse", ref)
	if err != nil {
		return "", fmt.Errorf("resolve %s in %s: %w: %s", ref, dir, err, out)
	}
	return strings.TrimSpace(out), nil
}

// git runs one git command and returns its combined output. The argv is always
// a vector, never a shell string, so a branch or path can never be a command.
func git(ctx context.Context, dir string, args ...string) (string, error) {
	cmd := exec.CommandContext(ctx, "git", args...)
	cmd.Dir = dir
	// A hook or a pager from the owner's environment would block a call that
	// has no terminal behind it.
	cmd.Env = append(os.Environ(), "GIT_PAGER=cat", "GIT_TERMINAL_PROMPT=0", "GIT_OPTIONAL_LOCKS=0")
	out, err := cmd.CombinedOutput()
	return string(out), err
}
